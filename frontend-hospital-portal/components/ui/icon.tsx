/**
 * An icon by its Material Symbols name. Sized by the font size (`text-[18px]`
 * and the like), as the icon font was; decorative, so hidden from screen
 * readers (the text or aria-label next to it names the control).
 */
export function Icon({ name, className }: { name: string; className?: string }) {
  const LucideIcon = ICONS[name] ?? Circle;
  if (process.env.NODE_ENV !== "production" && !ICONS[name]) {
    console.warn(`Icon: no lucide icon mapped for "${name}"`);
  }
  return <LucideIcon size="1em" aria-hidden="true" className={cn("shrink-0", className)} />;
}
